/**
 * KAI Advertisement Composer — deterministic factual rendering.
 *
 * Branch: experiment/kai-advertisement-composer. Imports nothing from
 * src/. Uses only npm packages (sharp, qrcode, jsqr, pngjs) plus the
 * repository's bundled font assets.
 *
 * CONTRACT
 *   The Composer owns 100% of factual rendering. The image model owns 0%.
 *   Input is a Creative Background PNG (artwork only, no text) plus the
 *   raw recruiter message. Every fact is parsed, source-grounded, and
 *   typeset here at coordinates this module computes — nothing about a
 *   fact's position, spelling or presence depends on a generative model.
 *
 * GUARANTEES
 *   - Auto-fit: type shrinks to fit its column, down to a legibility floor.
 *   - No truncation: text wraps; if it still cannot fit at the floor, the
 *     canvas grows. If it cannot fit even then, generation FAILS loudly
 *     with a layout-capacity error rather than silently dropping a fact.
 *   - No overlap: every row's height is measured from its own wrapped
 *     content before anything is drawn.
 *   - Real logo only: composited from a supplied asset file, never drawn.
 *   - Real QR only: generated by `qrcode`, then decoded back with `jsqr`
 *     to prove it scans before it ships.
 */
import path from "node:path";

// Point fontconfig at the repository's bundled Liberation faces before the
// first rasterization. librsvg resolves families through fontconfig only,
// so without this every glyph renders as a tofu box on a fontless host.
// This uses the font ASSETS, not any production module.
process.env.FONTCONFIG_FILE ??= path.join(process.cwd(), "src/server/generation/fonts/fonts.conf");

import sharp from "sharp";
import QRCode from "qrcode";
import jsQR from "jsqr";
import { PNG } from "pngjs";
import type { RecruiterFacts } from "./facts";

// ---------------------------------------------------------------- palette
const NAVY = "#12305C";
const NAVY_DEEP = "#0B1F3F";
const GREEN = "#7AB929";
const WHITE = "#FFFFFF";
const PANEL = "#F4F6F9";
const SLATE = "#5A6B7F";
const RULE = "#D8DEE6";

// ------------------------------------------------------------- typography
/** Average glyph width as a fraction of font size, by weight and case. */
function widthFactor(text: string, bold: boolean): number {
  const upper = text === text.toUpperCase() && /[A-Z]/.test(text);
  if (bold && upper) return 0.68;
  if (bold) return 0.6;
  return upper ? 0.62 : 0.56;
}

function textWidth(text: string, size: number, bold = false): number {
  return text.length * size * widthFactor(text, bold);
}

/** Shrinks toward `min` until the text fits `maxWidth`. Never truncates. */
function fitSize(text: string, maxWidth: number, preferred: number, min: number, bold = false): number {
  let size = preferred;
  while (size > min && textWidth(text, size, bold) > maxWidth) size -= 1;
  return Math.max(size, min);
}

/** Greedy word wrap. Returns every line — callers must not discard any. */
function wrap(text: string, maxWidth: number, size: number, bold = false): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (textWidth(candidate, size, bold) <= maxWidth || !line) {
      line = candidate;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function esc(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export class LayoutCapacityError extends Error {
  readonly code = "LAYOUT_CAPACITY";
  constructor(detail: string) {
    super(`Layout cannot hold every fact at minimum readability: ${detail}`);
    this.name = "LayoutCapacityError";
  }
}

// ------------------------------------------------------------------ QR
export interface QrResult {
  png: Buffer;
  url: string;
  decodable: boolean;
}

/**
 * A real QR, proven real: generated, then decoded back from its own
 * pixels. A QR that does not scan is worse than no QR at all, because it
 * looks like verification while providing none.
 */
export async function buildVerifiedQr(url: string): Promise<QrResult> {
  const png = await QRCode.toBuffer(url, { errorCorrectionLevel: "M", margin: 3, width: 512 });
  let decodable = false;
  try {
    const decoded = PNG.sync.read(png);
    const result = jsQR(new Uint8ClampedArray(decoded.data), decoded.width, decoded.height);
    decodable = result?.data === url;
  } catch {
    decodable = false;
  }
  return { png, url, decodable };
}

// -------------------------------------------------------------- layout
interface Row {
  title: string;
  titleLines: string[];
  titleSize: number;
  cells: { label: string; value: string; lines: string[]; size: number }[];
  height: number;
}

export interface ComposeInput {
  backgroundPng: Buffer;
  facts: RecruiterFacts;
  /** Real logo asset. Omitted means no logo is drawn — never a fabricated one. */
  logoPng?: Buffer | null;
  qr?: QrResult | null;
  widthPx?: number;
  heightPx?: number;
}

export async function compose(input: ComposeInput): Promise<Buffer> {
  const W = input.widthPx ?? 1080;
  const baseH = input.heightPx ?? 1350;
  const f = input.facts;

  const M = Math.round(W * 0.05); // page margin
  const FLOOR = Math.round(W * 0.015); // legibility floor
  const contentW = W - M * 2;

  // ---- Measure the position table first; its height drives the canvas.
  const COLS = [0.4, 0.22, 0.16, 0.22]; // title | qualification | experience | salary
  const gap = Math.round(W * 0.015);
  const colW = COLS.map((frac) => Math.round((contentW - gap * 3) * frac));

  // One uniform title size across every row. Fitting each title
  // independently made "Mechanical Engineer" tower over "Instrument
  // specialist (Fire system)" — the same class of information rendered at
  // different weights reads as a hierarchy that does not exist.
  const uniformTitleSize = f.positions.reduce(
    (smallest, p) => Math.min(smallest, fitSize(p.title, colW[0], Math.round(W * 0.036), FLOOR, true)),
    Math.round(W * 0.036),
  );

  const rows: Row[] = f.positions.map((p) => {
    const titleSize = uniformTitleSize;
    const titleLines = wrap(p.title, colW[0], titleSize, true);

    const cellDefs = [
      { label: "QUALIFICATION", value: p.qualification ?? "", w: colW[1] },
      { label: "EXPERIENCE", value: p.experience ?? "", w: colW[2] },
      { label: "SALARY", value: p.salary ?? "", w: colW[3] },
    ].filter((c) => c.value !== "");

    const cells = cellDefs.map((c) => {
      const size = fitSize(c.value, c.w, Math.round(W * 0.019), FLOOR);
      return { label: c.label, value: c.value, lines: wrap(c.value, c.w, size), size };
    });

    const titleH = titleLines.length * Math.round(titleSize * 1.16);
    const cellH = Math.max(
      0,
      ...cells.map((c) => Math.round(W * 0.016) * 1.6 + c.lines.length * Math.round(c.size * 1.35)),
    );
    const height = Math.max(titleH, cellH) + Math.round(W * 0.032);
    return { title: p.title, titleLines, titleSize, cells, height };
  });

  const tableH = rows.reduce((sum, r) => sum + r.height + Math.round(W * 0.011), 0);

  // ---- Fixed-height bands, then grow the canvas if the table needs it.
  const headerH = Math.round(W * 0.115);
  const headlineH = Math.round(W * 0.155);
  const notesH = f.notes.length ? Math.round(W * 0.03) + f.notes.length * Math.round(W * 0.033) : 0;
  const eligH =
    f.benefits.length || f.subjectLineInstruction
      ? Math.round(W * 0.035) +
        (f.benefits.length ? Math.round(W * 0.032) : 0) +
        (f.subjectLineInstruction ? Math.round(W * 0.055) : 0)
      : 0;
  const ctaH = Math.round(W * 0.105);
  const footerH = Math.round(W * 0.095);
  const tableHeadingH = Math.round(W * 0.062);

  const needed =
    headerH + headlineH + notesH + tableHeadingH + tableH + eligH + ctaH + footerH + Math.round(W * 0.03);
  const H = Math.max(baseH, needed);

  // Any leftover height becomes a hero band where the creative background
  // actually shows through, instead of a dead grey gap above the CTA. This
  // is the only place the artwork is visible — everywhere else the fact
  // layer is opaque by design, because contrast under text must be a
  // guarantee, not a property of whatever the image model produced.
  const heroH = Math.min(Math.max(0, H - needed), Math.round(H * 0.26));

  if (H > W * 4) {
    throw new LayoutCapacityError(
      `${f.positions.length} positions need a ${H}px canvas, beyond the ${Math.round(W * 4)}px publishable limit`,
    );
  }

  // ---- Draw.
  const parts: string[] = [`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">`];
  let y = 0;

  // HEADER — logo, agency name, registration.
  parts.push(`<rect x="0" y="0" width="${W}" height="${headerH}" fill="${WHITE}"/>`);
  const logoBox = Math.round(headerH * 0.62);
  let nameX = M;
  if (input.logoPng) {
    const logoDataUri = await toDataUri(input.logoPng, logoBox * 3);
    parts.push(
      `<image href="${logoDataUri}" x="${M}" y="${Math.round((headerH - logoBox) / 2)}" ` +
        `width="${Math.round(logoBox * 2.4)}" height="${logoBox}" preserveAspectRatio="xMinYMid meet"/>`,
    );
    nameX = M + Math.round(logoBox * 2.4) + Math.round(W * 0.02);
  }
  if (f.agencyName) {
    const s = fitSize(f.agencyName, contentW * 0.45, Math.round(W * 0.026), FLOOR, true);
    parts.push(
      `<text x="${nameX}" y="${Math.round(headerH * 0.56)}" font-family="KaiSans" font-size="${s}" ` +
        `font-weight="700" fill="${NAVY}">${esc(f.agencyName)}</text>`,
    );
  }
  if (f.registration) {
    const s = Math.round(W * 0.014);
    parts.push(
      `<text x="${W - M}" y="${Math.round(headerH * 0.56)}" font-family="KaiSans" font-size="${s}" ` +
        `fill="${SLATE}" text-anchor="end">${esc(f.registration)}</text>`,
    );
  }
  parts.push(`<rect x="0" y="${headerH - 4}" width="${W}" height="4" fill="${GREEN}"/>`);
  y = headerH;

  // HEADLINE — campaign title, country / industry.
  parts.push(`<rect x="0" y="${y}" width="${W}" height="${headlineH}" fill="${NAVY}"/>`);
  const titleSize = fitSize(f.campaignTitle, contentW, Math.round(W * 0.055), Math.round(W * 0.03), true);
  const titleLines = wrap(f.campaignTitle.toUpperCase(), contentW, titleSize, true);
  let ty = y + Math.round(headlineH * 0.38);
  for (const line of titleLines) {
    parts.push(
      `<text x="${M}" y="${ty}" font-family="KaiSans" font-size="${titleSize}" font-weight="700" ` +
        `fill="${WHITE}">${esc(line)}</text>`,
    );
    ty += Math.round(titleSize * 1.12);
  }
  const sub = [f.country, f.industry].filter(Boolean).join("  ·  ");
  if (sub) {
    const s = fitSize(sub, contentW, Math.round(W * 0.022), FLOOR);
    parts.push(
      `<text x="${M}" y="${y + headlineH - Math.round(headlineH * 0.16)}" font-family="KaiSans" ` +
        `font-size="${s}" fill="${GREEN}" letter-spacing="1">${esc(sub.toUpperCase())}</text>`,
    );
  }
  y += headlineH;

  // NOTES — mandatory conditions.
  if (notesH > 0) {
    parts.push(`<rect x="0" y="${y}" width="${W}" height="${notesH}" fill="${GREEN}"/>`);
    let ny = y + Math.round(W * 0.033);
    for (const note of f.notes) {
      const s = fitSize(note, contentW, Math.round(W * 0.019), FLOOR, true);
      for (const line of wrap(note, contentW, s, true)) {
        parts.push(
          `<text x="${M}" y="${ny}" font-family="KaiSans" font-size="${s}" font-weight="700" ` +
            `fill="${WHITE}">${esc(line)}</text>`,
        );
        ny += Math.round(s * 1.3);
      }
    }
    y += notesH;
  }

  // HERO — nothing is drawn here; the creative background shows through.
  y += heroH;

  // POSITION TABLE.
  parts.push(`<rect x="0" y="${y}" width="${W}" height="${H - y - ctaH - footerH}" fill="${PANEL}"/>`);
  const headingSize = Math.round(W * 0.026);
  parts.push(
    `<text x="${M}" y="${y + Math.round(tableHeadingH * 0.68)}" font-family="KaiSans" ` +
      `font-size="${headingSize}" font-weight="700" fill="${NAVY}" letter-spacing="2">POSITIONS AVAILABLE</text>`,
  );
  y += tableHeadingH;

  for (const row of rows) {
    parts.push(
      `<rect x="${M}" y="${y}" width="${contentW}" height="${row.height}" rx="${Math.round(W * 0.008)}" ` +
        `fill="${WHITE}" stroke="${RULE}" stroke-width="1"/>`,
    );
    const pad = Math.round(W * 0.018);
    let cy = y + pad + row.titleSize;
    for (const line of row.titleLines) {
      parts.push(
        `<text x="${M + pad}" y="${cy}" font-family="KaiSans" font-size="${row.titleSize}" ` +
          `font-weight="700" fill="${NAVY}">${esc(line)}</text>`,
      );
      cy += Math.round(row.titleSize * 1.16);
    }

    let cx = M + colW[0] + gap + pad;
    const labelSize = Math.round(W * 0.013);
    for (const cell of row.cells) {
      let vy = y + pad + labelSize;
      parts.push(
        `<text x="${cx}" y="${vy}" font-family="KaiSans" font-size="${labelSize}" font-weight="700" ` +
          `fill="${GREEN}" letter-spacing="1">${esc(cell.label)}</text>`,
      );
      vy += Math.round(labelSize * 1.7);
      for (const line of cell.lines) {
        parts.push(
          `<text x="${cx}" y="${vy}" font-family="KaiSans" font-size="${cell.size}" fill="${NAVY}">${esc(line)}</text>`,
        );
        vy += Math.round(cell.size * 1.35);
      }
      cx += (cell.label === "QUALIFICATION" ? colW[1] : cell.label === "EXPERIENCE" ? colW[2] : colW[3]) + gap;
    }
    y += row.height + Math.round(W * 0.011);
  }

  // ELIGIBILITY — benefits and subject-line instruction.
  if (eligH > 0) {
    y += Math.round(W * 0.008);
    if (f.benefits.length) {
      const text = f.benefits.join("   ·   ");
      const s = fitSize(text, contentW, Math.round(W * 0.019), FLOOR);
      parts.push(
        `<text x="${M}" y="${y + Math.round(W * 0.022)}" font-family="KaiSans" font-size="${s}" ` +
          `fill="${SLATE}">${esc(text)}</text>`,
      );
      y += Math.round(W * 0.032);
    }
    if (f.subjectLineInstruction) {
      const s = fitSize(f.subjectLineInstruction, contentW, Math.round(W * 0.017), FLOOR);
      const lines = wrap(f.subjectLineInstruction, contentW, s);
      let sy = y + Math.round(W * 0.022);
      for (const line of lines) {
        parts.push(
          `<text x="${M}" y="${sy}" font-family="KaiSans" font-size="${s}" fill="${SLATE}">${esc(line)}</text>`,
        );
        sy += Math.round(s * 1.35);
      }
    }
  }

  // CTA — email and phone, highest contrast on the canvas.
  const ctaY = H - footerH - ctaH;
  parts.push(`<rect x="0" y="${ctaY}" width="${W}" height="${ctaH}" fill="${NAVY}"/>`);
  parts.push(
    `<rect x="${M}" y="${ctaY + Math.round(ctaH * 0.26)}" width="${Math.round(W * 0.2)}" ` +
      `height="${Math.round(ctaH * 0.42)}" rx="${Math.round(ctaH * 0.21)}" fill="${GREEN}"/>`,
  );
  parts.push(
    `<text x="${M + Math.round(W * 0.1)}" y="${ctaY + Math.round(ctaH * 0.56)}" font-family="KaiSans" ` +
      `font-size="${Math.round(W * 0.021)}" font-weight="700" fill="${WHITE}" text-anchor="middle">APPLY NOW</text>`,
  );
  const contactBits = [f.email, f.mobile && f.mobile !== f.whatsapp ? f.mobile : null, f.whatsapp]
    .filter((v): v is string => Boolean(v))
    .filter((v, i, a) => a.indexOf(v) === i);
  if (contactBits.length) {
    const cx0 = M + Math.round(W * 0.23);
    const availW = W - cx0 - M;
    const s = fitSize(contactBits.join("    "), availW, Math.round(W * 0.026), FLOOR, true);
    parts.push(
      `<text x="${cx0}" y="${ctaY + Math.round(ctaH * 0.58)}" font-family="KaiSans" font-size="${s}" ` +
        `font-weight="700" fill="${WHITE}">${esc(contactBits.join("    "))}</text>`,
    );
  }

  // FOOTER — website, registration, real QR.
  const fy = H - footerH;
  parts.push(`<rect x="0" y="${fy}" width="${W}" height="${footerH}" fill="${NAVY_DEEP}"/>`);
  const qrSize = Math.round(footerH * 0.74);
  if (input.qr) {
    const qrUri = await toDataUri(input.qr.png, qrSize * 2);
    parts.push(
      `<rect x="${W - M - qrSize - 6}" y="${fy + Math.round((footerH - qrSize) / 2) - 6}" ` +
        `width="${qrSize + 12}" height="${qrSize + 12}" rx="4" fill="${WHITE}"/>`,
    );
    parts.push(
      `<image href="${qrUri}" x="${W - M - qrSize}" y="${fy + Math.round((footerH - qrSize) / 2)}" ` +
        `width="${qrSize}" height="${qrSize}"/>`,
    );
  }
  const footBits = [f.website, f.registration].filter(Boolean) as string[];
  let fby = fy + Math.round(footerH * 0.42);
  for (const bit of footBits) {
    const s = fitSize(bit, W - M * 2 - qrSize - Math.round(W * 0.04), Math.round(W * 0.017), FLOOR);
    parts.push(
      `<text x="${M}" y="${fby}" font-family="KaiSans" font-size="${s}" fill="${WHITE}">${esc(bit)}</text>`,
    );
    fby += Math.round(s * 1.5);
  }

  parts.push("</svg>");

  const factLayer = await sharp(Buffer.from(parts.join(""))).png().toBuffer();
  return sharp(input.backgroundPng)
    .resize(W, H, { fit: "cover" })
    .composite([{ input: factLayer, left: 0, top: 0 }])
    .png()
    .toBuffer();
}

async function toDataUri(png: Buffer, size: number): Promise<string> {
  const resized = await sharp(png).resize(size, size, { fit: "inside", withoutEnlargement: true }).png().toBuffer();
  return `data:image/png;base64,${resized.toString("base64")}`;
}
